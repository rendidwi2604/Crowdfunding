export function translate(language: Language, text: string): string {
  return language === 'en' ? english[text] ?? text : text;
}

export function localizedCampaign(campaign: Campaign, language: Language): Campaign {
  if (language !== 'en' || !demoDescriptions[campaign.id]) return campaign;
  return {
    ...campaign,
    title: translate(language, campaign.title),
    description: demoDescriptions[campaign.id],
    location: translate(language, campaign.location),
    organizer: translate(language, campaign.organizer),
  };
}
